// Build all distributables from packs/ + src/ (single source of truth).
//   dist/naturable.esm.js           ESM bundle (packs inlined) for web app / extension
//   dist/naturable.iife.js          <script> bundle, exposes window.Naturable
//   dist/packs.runtime.js           legacy: window.NATURABLE_PACKS (current naturable.app engine 2.2.0)
//   skill/scripts/naturable-check.mjs  self-contained CLI for the Agent Skill (Node 18+)
//   skill/references/rules-en.md, rules-zh.md  human/agent-readable rule reference

import { build } from "esbuild";
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { packs } from "../src/index.js";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url)));
const banner = `/* naturable-rules ${pkg.version} · packs ${packs.en.version} / ${packs.zh.version} · code MIT, rule data CC BY 4.0 */`;
mkdirSync("dist", { recursive: true });
mkdirSync("skill/scripts", { recursive: true });
mkdirSync("skill/references", { recursive: true });

await build({ entryPoints: ["src/index.js"], bundle: true, format: "esm", outfile: "dist/naturable.esm.js", banner: { js: banner }, target: "es2020" });
await build({ entryPoints: ["src/index.js"], bundle: true, format: "iife", globalName: "Naturable", outfile: "dist/naturable.iife.js", banner: { js: banner }, target: "es2020" });
await build({ entryPoints: ["src/cli.js"], bundle: true, platform: "node", format: "esm", outfile: "skill/scripts/naturable-check.mjs", banner: { js: `#!/usr/bin/env node\n${banner}` }, target: "node18" });

writeFileSync(
  "dist/packs.runtime.js",
  `/* Auto-generated from packs/*.json — do not edit by hand. */\nwindow.NATURABLE_PACKS = ${JSON.stringify({ ...packs, meta: { engine_pack_api: 1, default_en: packs.en.version, default_zh: packs.zh.version } })};\n`
);

// ---- Markdown references ----
const SEV = { strong: "strong", suggestion: "suggestion" };
const describeDetect = (d) =>
  d.type === "regex"
    ? "`" + d.pattern.replace(/`/g, "\\`").replace(/\|/g, "\\|") + "`"
    : `heuristic \`${d.name}\`${d.params ? " " + JSON.stringify(d.params) : ""}`;

function reference(pack, lang) {
  const zh = lang === "zh";
  const lines = [];
  lines.push(`# Naturable rules — ${zh ? "Chinese (beta)" : "English"} · ${pack.version}`);
  lines.push("");
  lines.push(`Generated from \`packs/${lang}.json\`. Do not edit by hand.`);
  lines.push("");
  lines.push("Layers run in this order and win overlaps in this order: **hollow → structure → artifact → lexicon**.");
  lines.push("`strong` = clear pattern; `suggestion` = worth a look. `safe fix` = can be applied automatically without changing meaning, numbers or names.");
  lines.push("");
  for (const layer of pack.layer_order) {
    const rules = pack.rules.filter((r) => r.layer === layer);
    if (!rules.length) continue;
    lines.push(`## ${layer}`);
    lines.push("");
    for (const r of rules) {
      lines.push(`### ${zh ? r.name_zh : r.name_en} — \`${r.id}\``);
      lines.push("");
      lines.push(`- **Severity:** ${SEV[r.severity]} · **category:** ${r.category} · **confidence:** ${r.confidence}${r.auto ? " · **safe fix**" : ""}`);
      lines.push(`- **Why:** ${r.reason}`);
      lines.push(`- **Do:** ${r.rewrite}`);
      lines.push(`- **Before:** ${r.before}`);
      lines.push(`- **After:** ${r.after}`);
      lines.push(`- **Detects:** ${describeDetect(r.detect)}`);
      if (r.docs) lines.push(`- **Learn more:** ${r.docs}`);
      lines.push("");
    }
  }
  if (pack.banned_rules?.length) {
    lines.push("## Rules deliberately NOT applied");
    lines.push("");
    lines.push("These were tested and rejected. Do not suggest them.");
    lines.push("");
    for (const b of pack.banned_rules) lines.push(`- **${b.label}** (\`${b.id}\`): ${b.reason}`);
    lines.push("");
  }
  return lines.join("\n");
}

writeFileSync("skill/references/rules-en.md", reference(packs.en, "en"));
writeFileSync("skill/references/rules-zh.md", reference(packs.zh, "zh"));
// ---- README rules index (between markers) ----
const CAT = { evidence: "Evidence", sentence: "Sentence", structure: "Structure", rhythm: "Rhythm", artifact: "Assistant leftovers", vocabulary: "Vocabulary" };
function rulesIndex() {
  const out = ["<!-- rules-index:start (generated by scripts/build.mjs from packs/*.json; do not edit) -->", ""];
  for (const [lang, pack] of [["en", packs.en], ["zh", packs.zh]]) {
    out.push(`### ${lang === "en" ? "English" : "Chinese (beta)"} · ${pack.version} · ${pack.rules.length} rules`, "");
    for (const [cat, label] of Object.entries(CAT)) {
      const rules = pack.rules.filter((r) => r.category === cat);
      if (!rules.length) continue;
      const name = (r) => (lang === "zh" ? `${r.name_zh} (${r.name_en})` : r.name_en);
      out.push(`- **${label}:** ` + rules.map((r) => `[${name(r)}](${r.docs})`).join(" · "));
    }
    out.push("");
  }
  out.push("<!-- rules-index:end -->");
  return out.join("\n");
}
const readme = readFileSync("README.md", "utf8");
const marked = /<!-- rules-index:start[\s\S]*?<!-- rules-index:end -->/;
if (!marked.test(readme)) throw new Error("README.md is missing the rules-index markers");
writeFileSync("README.md", readme.replace(marked, rulesIndex()));

console.log(`built ${pkg.version}: ${packs.en.rules.length} en + ${packs.zh.rules.length} zh rules`);
